'use strict';
// Camada de dados em PostgreSQL (Neon / Vercel Postgres). Só SQL parametrizado.
const crypto = require('crypto');

const iso = (d) => (d ? new Date(d).toISOString() : null);
const mapUser = (r) => r && ({
  id: r.id, name: r.name, email: r.email, phone: r.phone || '', role: r.role,
  passwordHash: r.password_hash, tokenVersion: Number(r.token_version),
  failedLogins: Number(r.failed_logins), lockedUntil: iso(r.locked_until), createdAt: iso(r.created_at),
});
const mapProduct = (r) => r && ({
  id: r.id, name: r.name, brand: r.brand, category: r.category, tags: r.tags || [],
  priceCents: Number(r.price_cents), image: r.image, color: r.color, sizes: r.sizes || [],
  stock: r.stock === null || r.stock === undefined ? null : Number(r.stock),
  description: r.description, bestseller: r.bestseller, isNew: r.is_new, active: r.active,
  createdAt: iso(r.created_at), updatedAt: iso(r.updated_at),
});
const mapOrder = (r) => r && ({
  id: r.id, number: Number(r.number), userId: r.user_id, sessionId: r.stripe_session_id,
  status: r.status, totalCents: Number(r.total_cents), shippingCents: Number(r.shipping_cents),
  items: r.items || [], shippingAddress: r.shipping_address || null,
  customerName: r.customer_name || '', customerEmail: r.customer_email || '', customerPhone: r.customer_phone || '',
  trackingCode: r.tracking_code || '', timeline: r.timeline || [],
  createdAt: iso(r.created_at), paidAt: iso(r.paid_at), updatedAt: iso(r.updated_at),
  userName: r.user_name, userEmail: r.user_email,
});

const DDL = [
  `CREATE TABLE IF NOT EXISTS users (
    id uuid PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL UNIQUE,
    phone text,
    password_hash text NOT NULL,
    role text NOT NULL DEFAULT 'customer',
    token_version integer NOT NULL DEFAULT 0,
    failed_logins integer NOT NULL DEFAULT 0,
    locked_until timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE TABLE IF NOT EXISTS products (
    id text PRIMARY KEY,
    name text NOT NULL,
    brand text NOT NULL DEFAULT '',
    category text NOT NULL DEFAULT '',
    tags jsonb NOT NULL DEFAULT '[]',
    price_cents integer NOT NULL,
    image text NOT NULL DEFAULT '',
    color text NOT NULL DEFAULT '#333333',
    sizes jsonb NOT NULL DEFAULT '[]',
    stock integer,
    description text NOT NULL DEFAULT '',
    bestseller boolean NOT NULL DEFAULT false,
    is_new boolean NOT NULL DEFAULT false,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE TABLE IF NOT EXISTS orders (
    id uuid PRIMARY KEY,
    number bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    user_id uuid NOT NULL REFERENCES users(id),
    stripe_session_id text UNIQUE,
    status text NOT NULL DEFAULT 'pendente',
    total_cents integer NOT NULL,
    shipping_cents integer NOT NULL DEFAULT 0,
    items jsonb NOT NULL,
    shipping_address jsonb,
    customer_name text,
    customer_email text,
    customer_phone text,
    tracking_code text,
    timeline jsonb NOT NULL DEFAULT '[]',
    created_at timestamptz NOT NULL DEFAULT now(),
    paid_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE INDEX IF NOT EXISTS orders_user_idx ON orders (user_id, created_at DESC)`,
  `CREATE INDEX IF NOT EXISTS orders_created_idx ON orders (created_at DESC)`,
];

let _sql;
function sqlClient() {
  if (!_sql) {
    const { neon } = require('@neondatabase/serverless');
    const c = neon(process.env.DATABASE_URL);
    _sql = (text, params = []) => c.query(text, params);
  }
  return _sql;
}

function create(sqlOverride) {
  const q = (t, p) => (sqlOverride || sqlClient())(t, p);

  const ORDER_SELECT = `SELECT o.*, u.name AS user_name, u.email AS user_email FROM orders o JOIN users u ON u.id = o.user_id`;

  const impl = {
    /* ---------- usuários ---------- */
    async createUser({ name, email, phone, passwordHash, role = 'customer' }) {
      const rows = await q(
        `INSERT INTO users (id, name, email, phone, password_hash, role) VALUES ($1,$2,$3,$4,$5,$6)
         ON CONFLICT (email) DO NOTHING RETURNING *`,
        [crypto.randomUUID(), name, email, phone || null, passwordHash, role]
      );
      if (!rows.length) { const e = new Error('EMAIL_TAKEN'); e.code = 'EMAIL_TAKEN'; throw e; }
      return mapUser(rows[0]);
    },
    async getUserByEmail(email) { return mapUser((await q(`SELECT * FROM users WHERE email = $1`, [email]))[0]); },
    async getUserById(id) { return mapUser((await q(`SELECT * FROM users WHERE id = $1`, [id]))[0]); },
    async updateProfile(id, { name, phone }) {
      return mapUser((await q(`UPDATE users SET name = $2, phone = $3 WHERE id = $1 RETURNING *`, [id, name, phone || null]))[0]);
    },
    async setPassword(id, hash) {
      return mapUser((await q(
        `UPDATE users SET password_hash = $2, token_version = token_version + 1, failed_logins = 0, locked_until = NULL WHERE id = $1 RETURNING *`,
        [id, hash]))[0]);
    },
    async recordLoginFailure(id, maxFails, lockMinutes) {
      const r = (await q(
        `UPDATE users SET failed_logins = failed_logins + 1,
           locked_until = CASE WHEN failed_logins + 1 >= $2::int THEN now() + make_interval(mins => $3::int) ELSE locked_until END
         WHERE id = $1 RETURNING failed_logins, locked_until`, [id, maxFails, lockMinutes]))[0];
      return { failedLogins: Number(r.failed_logins), lockedUntil: iso(r.locked_until) };
    },
    async clearLoginFailures(id) {
      await q(`UPDATE users SET failed_logins = 0, locked_until = NULL WHERE id = $1 AND (failed_logins <> 0 OR locked_until IS NOT NULL)`, [id]);
    },
    async countCustomers(sinceIso) {
      const r = (await q(
        `SELECT count(*) AS total, count(*) FILTER (WHERE created_at >= $1::timestamptz) AS recent FROM users WHERE role = 'customer'`, [sinceIso]))[0];
      return { total: Number(r.total), recent: Number(r.recent) };
    },
    async listCustomers() {
      const rows = await q(
        `SELECT u.id, u.name, u.email, u.phone, u.created_at,
           count(o.id) FILTER (WHERE o.status NOT IN ('pendente','cancelado')) AS orders_count,
           COALESCE(sum(o.total_cents) FILTER (WHERE o.status NOT IN ('pendente','cancelado')), 0) AS spent_cents,
           max(o.created_at) AS last_order_at
         FROM users u LEFT JOIN orders o ON o.user_id = u.id
         WHERE u.role = 'customer' GROUP BY u.id ORDER BY u.created_at DESC LIMIT 2000`);
      return rows.map((r) => ({
        id: r.id, name: r.name, email: r.email, phone: r.phone || '', createdAt: iso(r.created_at),
        ordersCount: Number(r.orders_count), spentCents: Number(r.spent_cents), lastOrderAt: iso(r.last_order_at),
      }));
    },

    /* ---------- produtos ---------- */
    async listProducts({ activeOnly = false } = {}) {
      const rows = await q(`SELECT * FROM products ${activeOnly ? 'WHERE active' : ''} ORDER BY created_at ASC, id ASC`);
      return rows.map(mapProduct);
    },
    async getProduct(id) { return mapProduct((await q(`SELECT * FROM products WHERE id = $1`, [id]))[0]); },
    async insertProduct(p) {
      const rows = await q(
        `INSERT INTO products (id,name,brand,category,tags,price_cents,image,color,sizes,stock,description,bestseller,is_new,active)
         VALUES ($1,$2,$3,$4,$5::jsonb,$6,$7,$8,$9::jsonb,$10,$11,$12,$13,$14)
         ON CONFLICT (id) DO NOTHING RETURNING *`,
        [p.id, p.name, p.brand, p.category, JSON.stringify(p.tags), p.priceCents, p.image, p.color, JSON.stringify(p.sizes),
          p.stock, p.description, p.bestseller, p.isNew, p.active]);
      return mapProduct(rows[0]);
    },
    async updateProduct(id, p) {
      const rows = await q(
        `UPDATE products SET name=$2, brand=$3, category=$4, tags=$5::jsonb, price_cents=$6, image=$7, color=$8, sizes=$9::jsonb,
           stock=$10, description=$11, bestseller=$12, is_new=$13, active=$14, updated_at=now()
         WHERE id=$1 RETURNING *`,
        [id, p.name, p.brand, p.category, JSON.stringify(p.tags), p.priceCents, p.image, p.color, JSON.stringify(p.sizes),
          p.stock, p.description, p.bestseller, p.isNew, p.active]);
      return mapProduct(rows[0]);
    },
    async decrementStock(id, qty) {
      await q(`UPDATE products SET stock = GREATEST(stock - $2::int, 0), updated_at = now() WHERE id = $1 AND stock IS NOT NULL`, [id, qty]);
    },

    /* ---------- pedidos ---------- */
    async createOrder(o) {
      const rows = await q(
        `INSERT INTO orders (id,user_id,stripe_session_id,status,total_cents,shipping_cents,items,customer_name,customer_email,timeline)
         VALUES ($1,$2,$3,'pendente',$4,$5,$6::jsonb,$7,$8,$9::jsonb) RETURNING *`,
        [o.id, o.userId, o.sessionId, o.totalCents, o.shippingCents, JSON.stringify(o.items), o.customerName, o.customerEmail,
          JSON.stringify([{ status: 'pendente', at: new Date().toISOString(), note: 'Pedido criado, aguardando pagamento' }])]);
      return mapOrder(rows[0]);
    },
    async getOrderById(id) { return mapOrder((await q(`${ORDER_SELECT} WHERE o.id = $1`, [id]))[0]); },
    async getOrderBySession(sid) { return mapOrder((await q(`${ORDER_SELECT} WHERE o.stripe_session_id = $1`, [sid]))[0]); },
    async listOrdersByUser(userId) {
      return (await q(`${ORDER_SELECT} WHERE o.user_id = $1 ORDER BY o.created_at DESC LIMIT 200`, [userId])).map(mapOrder);
    },
    async listOrders({ status, limit = 500 } = {}) {
      return (await q(`${ORDER_SELECT} WHERE ($1::text IS NULL OR o.status = $1) ORDER BY o.created_at DESC LIMIT $2::int`,
        [status || null, limit])).map(mapOrder);
    },
    async ordersSince(sinceIso, limit = 10000) {
      return (await q(`${ORDER_SELECT} WHERE o.created_at >= $1::timestamptz ORDER BY o.created_at DESC LIMIT $2::int`, [sinceIso, limit])).map(mapOrder);
    },
    async markOrderPaid(id, { shippingAddress, customerName, customerEmail, customerPhone }) {
      const ev = [{ status: 'pago', at: new Date().toISOString(), note: 'Pagamento confirmado' }];
      const rows = await q(
        `UPDATE orders SET status='pago', paid_at=now(), updated_at=now(),
           shipping_address=$2::jsonb, customer_name=COALESCE($3, customer_name),
           customer_email=COALESCE($4, customer_email), customer_phone=COALESCE($5, customer_phone),
           timeline = timeline || $6::jsonb
         WHERE id=$1 AND status='pendente' RETURNING *`,
        [id, shippingAddress ? JSON.stringify(shippingAddress) : null, customerName || null, customerEmail || null, customerPhone || null, JSON.stringify(ev)]);
      return mapOrder(rows[0]); // undefined se já estava pago (idempotente)
    },
    async markOrderCancelled(id, note) {
      const ev = [{ status: 'cancelado', at: new Date().toISOString(), note }];
      return mapOrder((await q(
        `UPDATE orders SET status='cancelado', updated_at=now(), timeline = timeline || $2::jsonb WHERE id=$1 AND status='pendente' RETURNING *`,
        [id, JSON.stringify(ev)]))[0]);
    },
    async updateOrderAdmin(id, { status, trackingCode, note }) {
      const ev = [{ status, at: new Date().toISOString(), note: note || '' }];
      return mapOrder((await q(
        `UPDATE orders SET status=$2, tracking_code=$3, updated_at=now(),
           paid_at = CASE WHEN $2 IN ('pago','em_separacao','enviado','entregue') AND paid_at IS NULL THEN now() ELSE paid_at END,
           timeline = timeline || $4::jsonb
         WHERE id=$1 RETURNING *`, [id, status, trackingCode || null, JSON.stringify(ev)]))[0]);
    },
  };

  async function init({ seedProducts = [], admin } = {}) {
    for (const stmt of DDL) await q(stmt);
    const c = await q(`SELECT count(*) AS n FROM products`);
    if (Number(c[0].n) === 0) for (const p of seedProducts) await impl.insertProduct(p);
    if (admin) {
      try { await impl.createUser({ ...admin, role: 'admin' }); } catch (e) { if (e.code !== 'EMAIL_TAKEN') throw e; }
    }
  }
  return { impl, init };
}

module.exports = { create };
